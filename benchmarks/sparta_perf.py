#!/usr/bin/env python3
"""Performance comparison with SPARTA on identical hardware (M6.12).

Both codes run the same DSMC case (geometry, gas, wall model, cell size, time
step, particle weight, warm-up and sampling length). The figure of merit is
the time needed for a given statistical accuracy of the drag force,

    E = SE(F_x)^2 * t        (lower is better; independent of the run length)

with SE from 20 block averages of the sampling phase, computed the same way
for both codes (vleo_solver: its own block statistics; SPARTA: the per-step
surface force from `compute surf` + `compute reduce`, block-averaged here).
t is the wall time of the time loop: SPARTA's two "Loop time" values
(warm-up + sampling); vleo_solver's `wall_time_s` (time loop plus set-up and
fill, i.e. slightly conservative for vleo_solver).

SPARTA runs with its Kokkos styles on GPUs (-k on g N -sf kk). Only styles
with Kokkos versions are used (no fix ave/surf, which has none).

  sparta_perf.py --label w7700 --mpiexec mpiexec
      --vleo build/hip-gfx1101-mpi/vleo_solver --vleo-ranks 1 2
      --sparta-kk ~/workspace/sparta/build-hip/src/spa_kokkos_hip --gpu-ranks 1 2
      --sparta-cpu ~/workspace/sparta/build-mpi/src/spa_mpi --cpu-ranks 32 64
      [--cases P1 P2] [--quick]
-> benchmarks/results/sparta-perf-<label>.json and a Markdown table.
Python 3.6 compatible.
"""
import argparse
import json
import math
import os
import pathlib
import re
import shlex
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "validation" / "sparta"))
import run_cases as rc  # noqa: E402  (species data, cube geometry, SPARTA file writers)

BOX = rc.BOX
VSTREAM = rc.VSTREAM
TW = 300.0
BLOCKS = 20

# Transitional flow (Kn ~ 1 on the 0.5 m cube), Ar, VHS, diffuse wall. Cells
# are finer than the accuracy requires so that the GPUs are filled.
CASES = {
    "P1": dict(cells=26, desc="cube, Ar, Kn ~ 1, 26^3 cells, ~0.8 M particles"),
    "P2": dict(cells=52, desc="cube, Ar, Kn ~ 1, 52^3 cells, ~6 M particles"),
}
GAS, N_RHO, T_GAS, PPC = "Ar", 3e18, 900.0, 20


def numerics(case, quick):
    m = rc.SPECIES[GAS][0] * rc.AMU
    c_mp = math.sqrt(2 * rc.KB * T_GAS / m)
    v = math.sqrt(sum(x * x for x in VSTREAM))
    dx = 2 * BOX / case["cells"]
    dt = dx / (4.0 * (v + 3.0 * c_mp))
    flow_through = 2 * BOX / (v * dt)  # steps
    warmup = int(math.ceil(3 * flow_through / 100.0)) * 100
    sample = (500 if quick else 2000)
    return dict(dx=dx, dt=dt, fnum=N_RHO * dx ** 3 / PPC, warmup=warmup, sample=sample)


def sparta_input(case, num):
    return "\n".join([
        "# generated by benchmarks/sparta_perf.py (M6.12)",
        "seed 12345",
        "dimension 3",
        "global gridcut 0.0 comm/sort yes",
        "boundary o o o",
        "create_box %r %r %r %r %r %r" % (-BOX, BOX, -BOX, BOX, -BOX, BOX),
        "create_grid %d %d %d" % (case["cells"], case["cells"], case["cells"]),
        "balance_grid rcb cell",
        "global nrho %r fnum %r" % (N_RHO, num["fnum"]),
        "species case.species %s" % GAS,
        "mixture gas %s vstream %r %r %r temp %r" % (GAS, VSTREAM[0], VSTREAM[1], VSTREAM[2], T_GAS),
        "read_surf cube.surf",
        "surf_collide 1 diffuse %r 1.0" % TW,
        "surf_modify all collide 1",
        "collide vss gas case.vss",
        "collide_modify vremax 100 yes",
        "fix in emit/face gas all",
        "create_particles gas n 0",
        "timestep %r" % num["dt"],
        "stats 100",
        "stats_style step cpu np",
        "run %d" % num["warmup"],
        "compute 1 surf all gas fx fy fz etot norm flow",
        "compute 2 reduce sum c_1[1] c_1[2] c_1[3] c_1[4]",
        "stats 1",
        "stats_style step cpu np c_2[1] c_2[2] c_2[3] c_2[4]",
        "run %d" % num["sample"],
    ]) + "\n"


def vleo_config(case, num, name):
    return (
        "simulation: {name: %s, mode: dsmc, random_seed: 2026}\n" % name +
        "geometry: {file: cube.stl}\n"
        "domain: {box_min_m: [%r, %r, %r], box_max_m: [%r, %r, %r]}\n" % (-BOX, -BOX, -BOX, BOX, BOX, BOX) +
        "reference: {area_m2: 0.25, length_m: 0.5, moment_center_m: [0, 0, 0], lift_axis_body: [0, 0, 1]}\n"
        "gas: {number_density_m3: %r, translational_temperature_K: %r, " % (N_RHO, T_GAS) +
        "bulk_velocity_body_mps: [%r, %r, %r], species: {%s: 1.0}}\n" % (VSTREAM[0], VSTREAM[1], VSTREAM[2], GAS) +
        "surface: {model: maxwell, temperature_K: %r, maxwell: {diffuse_fraction: 1.0}}\n" % TW +
        "dsmc: {collision_model: VHS, cell_size_mode: fixed, cell_size_m: %r, " % num["dx"] +
        "timestep_mode: fixed, timestep_s: %r, particles_per_cell_target: %d, " % (num["dt"], PPC) +
        "warmup_steps: %d, sample_steps: %d, blocks: %d}\n" % (
            num["warmup"], num["sample"], BLOCKS))


def blocks_mean_se(values, blocks):
    n = len(values) // blocks
    means = [sum(values[k * n:(k + 1) * n]) / n for k in range(blocks)]
    m = sum(means) / blocks
    var = sum((x - m) ** 2 for x in means) / (blocks - 1)
    return m, math.sqrt(var / blocks)


def parse_sparta(log):
    text = pathlib.Path(log).read_text()
    loops = [float(x) for x in re.findall(r"^Loop time of ([0-9.eE+-]+) on", text, re.M)]
    fx, in_sample, first = [], False, True
    for line in text.splitlines():
        if line.startswith("Step") and "c_2[1]" in line:
            in_sample = True
            continue
        if in_sample:
            if line.startswith("Loop time"):
                break
            parts = line.split()
            if len(parts) == 7 and parts[0].isdigit():
                if first:  # row at the start of the run: no sample yet
                    first = False
                    continue
                fx.append(float(parts[3]))
    moves = re.findall(r"^Particle-moves/step: ([0-9.eE+-]+)", text, re.M)
    return dict(loop_times_s=loops, fx=fx, particles=float(moves[-1]) if moves else None)


def run(cmd, cwd, log):
    print("$ " + " ".join(cmd), flush=True)
    with open(str(log), "w") as f:
        rc_ = subprocess.call(cmd, cwd=str(cwd), stdout=f, stderr=subprocess.STDOUT)
    if rc_ != 0:
        raise SystemExit("command failed (%d), see %s" % (rc_, log))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--label", required=True)
    ap.add_argument("--mpiexec", default="mpiexec")
    ap.add_argument("--mpiexec-flags", default="")
    ap.add_argument("--vleo")
    ap.add_argument("--vleo-ranks", type=int, nargs="+", default=[1])
    ap.add_argument("--sparta-kk")
    ap.add_argument("--gpu-ranks", type=int, nargs="+", default=[1])
    ap.add_argument("--sparta-cpu")
    ap.add_argument("--cpu-ranks", type=int, nargs="+", default=[])
    ap.add_argument("--cases", nargs="+", default=list(CASES))
    ap.add_argument("--quick", action="store_true", help="500 sampling steps (pipeline test)")
    ap.add_argument("--workdir", default=str(ROOT / "benchmarks" / "sparta_perf_runs"))
    args = ap.parse_args()
    launch = [args.mpiexec] + shlex.split(args.mpiexec_flags)

    out = {"label": args.label, "method": "E = SE(F_x)^2 * t, %d blocks" % BLOCKS, "cases": {}}
    for name in args.cases:
        case = CASES[name]
        num = numerics(case, args.quick)
        d = pathlib.Path(args.workdir) / args.label / name
        d.mkdir(parents=True, exist_ok=True)
        tris = rc.cube_triangles()
        rc.write_stl(d / "cube.stl", tris)
        rc.write_sparta_surf(d / "cube.surf", tris)
        rc.sparta_species_files(d, GAS)
        (d / "in.case").write_text(sparta_input(case, num))
        (d / "vleo.yaml").write_text(vleo_config(case, num, name))
        print("[%s] %s: dx %.4g m, dt %.4g s, warm-up %d + sampling %d steps" % (
            name, case["desc"], num["dx"], num["dt"], num["warmup"], num["sample"]), flush=True)
        runs = []
        for n in args.vleo_ranks if args.vleo else []:
            o = d / ("vleo_np%d" % n)
            run(launch + ["-n", str(n), os.path.abspath(args.vleo), "-q", "-c", "vleo.yaml", "-o", str(o)], d,
                d / ("vleo_np%d.log" % n))
            r = json.loads((o / "results.json").read_text())
            runs.append(dict(code="vleo_solver", device="GPU" if n else "", ranks=n,
                             t=r["diagnostics"]["wall_time_s"], fx=r["results"]["force_N"][0],
                             se=r["std_error"]["force_N"][0], particles=r["diagnostics"]["particles_mean"]))
        for kind, binary, ranks in (("kk", args.sparta_kk, args.gpu_ranks), ("cpu", args.sparta_cpu, args.cpu_ranks)):
            if not binary:
                continue
            for n in ranks:
                extra = ["-k", "on", "g", str(n), "-sf", "kk"] if kind == "kk" else []
                log = d / ("sparta_%s_np%d.log" % (kind, n))
                run(launch + ["-n", str(n), os.path.abspath(binary)] + extra + ["-in", "in.case"], d, log)
                p = parse_sparta(log)
                if len(p["fx"]) < num["sample"]:
                    raise SystemExit("%s: %d force samples, expected %d" % (log, len(p["fx"]), num["sample"]))
                m, se = blocks_mean_se(p["fx"][:num["sample"]], BLOCKS)
                runs.append(dict(code="SPARTA " + ("Kokkos HIP" if kind == "kk" else "CPU MPI"), ranks=n,
                                 t=sum(p["loop_times_s"][-2:]), fx=m, se=se, particles=p["particles"]))
        for x in runs:
            x["E"] = x["se"] ** 2 * x["t"]
        out["cases"][name] = dict(description=case["desc"], numerics=num, runs=runs)

    res = ROOT / "benchmarks" / "results"
    res.mkdir(parents=True, exist_ok=True)
    path = res / ("sparta-perf-%s.json" % args.label)
    path.write_text(json.dumps(out, indent=2) + "\n")
    print("wrote %s\n" % path)
    for name, c in out["cases"].items():
        base = min(x["E"] for x in c["runs"])
        print("%s: %s" % (name, c["description"]))
        print("| code | ranks | particles | t [s] | F_x [N] | SE [N] | E = SE^2 t | E / best |")
        print("| ---- | ----- | --------- | ----- | ------- | ------ | ---------- | -------- |")
        for x in c["runs"]:
            print("| %s | %d | %.3g | %.2f | %.5g | %.2g | %.3g | %.2f |" % (
                x["code"], x["ranks"], x["particles"] or 0, x["t"], x["fx"], x["se"], x["E"], x["E"] / base))
        print()


if __name__ == "__main__":
    main()
