#!/usr/bin/env python3
"""Performance benchmarks (M5.1, M5.2, M5.4).

Runs the benchmark cases with --profile and records, per case: wall time,
throughput (TPMC histories/s, DSMC particle steps/s), the phase profile and the
efficiency  E = SE(C_D)^2 * wall time  (time needed per unit of statistical
accuracy; lower is better, independent of the run length).

  benchmark.py run <vleo_solver> <label> [--cases B1 B2 ...]   -> benchmarks/results/<label>.json
  benchmark.py compare <before.json> <after.json>                -> speed-up table

Verification cases (V*, docs/verification.md "Performance"): the solver
configurations of the verification stages, shortened to a fixed number of steps
(the same on every backend), cell-state output removed. For a GPU / CPU
comparison run them with both builds and compare:
  benchmark.py run build/hip-gfx1101/vleo_solver w7700 --cases V --repeat 1
  OMP_NUM_THREADS=32 OMP_PROC_BIND=spread OMP_PLACES=threads \
      benchmark.py run build/cpu-release/vleo_solver cpu32 --cases V --repeat 1
  benchmark.py compare benchmarks/results/cpu32.json benchmarks/results/w7700.json
The performance index is the time of the step loop per particle and step
(DSMC, ns) or per history (TPMC, ns); the set-up (geometry, grid, fill) is not
included. The sphere and cone STL files are generated by
verification/make_sphere_configs.py and make_cone_configs.py.

Scaling with the particle number (S*): the sphere of verification stage 3
(argon, Ma 4, Kn 0.3) with 10 particles per cell and cells from 20 mm down to
2 mm, i.e. ~40 k to ~40 M particles; same physics and time step, the number of
steps chosen so that every point does ~1e9 particle steps (200 ... 20 000):
  benchmark.py run <solver> <label> --cases S --repeat 1
  benchmark.py plot benchmarks/results/<cpu>.json benchmarks/results/<gpu>.json --png scaling.png

Several GPUs (M6.7, MPI builds): --ranks N [--mpiexec mpiexec] [--mpiexec-flags "..."]
starts the solver with N ranks; --scale K multiplies the problem size (DSMC
particles per cell, TPMC histories) for weak scaling, e.g.
  benchmark.py run <solver> w7700-np1 --cases B3 B4
  benchmark.py run <solver> w7700-np2 --cases B3 B4 --ranks 2           (strong)
  benchmark.py run <solver> w7700-np2-weak --cases B3 B4 --ranks 2 --scale 2
"""
