#!/usr/bin/env python3
"""Normal-shock verification cases in argon (docs/verification.md).

    verification/make_shock_configs.py [--mach 1.4 2 3 5 8] [--out verification]

Writes shock_ma<M>.yaml per Mach number and batch_shock.txt. Each case is a
tube x in [-30, 30] lambda1 between two inflow faces with the upstream state
(n1 = 1e21 m^-3, T1 = 273 K) and the Rankine-Hugoniot downstream state,
started from the jump (fill_depth_m); 4 x 4 cells across, specular sides.
Cells lambda1 / 4; the time step resolves the downstream collision time and
keeps a molecule at u + 2 c_mp below one cell per step.
Evaluate with verification/shock_profile.py results/shock_ma<M>.
"""
import argparse
import math
import os

K_B = 1.380649e-23
M_AR = 39.948 * 1.66053906660e-27
D_REF, OMEGA, T_REF = 4.17e-10, 0.81, 273.0  # Bird (1994), VHS argon
GAMMA = 5.0 / 3.0


def rankine_hugoniot(M):
    g, M2 = GAMMA, M * M
    r = (g + 1) * M2 / ((g - 1) * M2 + 2)
    t = (2 * g * M2 - (g - 1)) * ((g - 1) * M2 + 2) / ((g + 1) ** 2 * M2)
    return r, 1.0 / r, t


def vhs_lambda_tau(n, T):
    """Mean free path and collision time of VHS argon (c_mean / nu, 1 / nu)."""
    mr = 0.5 * M_AR
    # equilibrium <sigma g> = 2 sqrt(pi) d^2 (T / T_ref)^(1 - omega) sqrt(2 k T_ref / m_r)
    sg = 2 * math.sqrt(math.pi) * D_REF ** 2 * (T / T_REF) ** (1 - OMEGA) * math.sqrt(2 * K_B * T_REF / mr)
    nu = n * sg
    c_mean = math.sqrt(8 * K_B * T / (math.pi * M_AR))
    return c_mean / nu, 1.0 / nu


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mach", type=float, nargs="+", default=[1.4, 2.0, 3.0, 5.0, 8.0])
    ap.add_argument("--out", default=os.path.dirname(os.path.abspath(__file__)))
    ap.add_argument("--n1", type=float, default=1e21)
    ap.add_argument("--T1", type=float, default=273.0)
    ap.add_argument("--ppc", type=int, default=50)
    a = ap.parse_args()

    batch = []
    for M in a.mach:
        n1, T1 = a.n1, a.T1
        r, ur, tr = rankine_hugoniot(M)
        n2, T2 = n1 * r, T1 * tr
        u1 = M * math.sqrt(GAMMA * K_B * T1 / M_AR)
        u2 = u1 * ur
        lam1, tau1 = vhs_lambda_tau(n1, T1)
        _, tau2 = vhs_lambda_tau(n2, T2)
        L = 60.0 * lam1
        dx = lam1 / 4.0
        w = 4 * dx
        c_mp2 = math.sqrt(2 * K_B * T2 / M_AR)
        c_mp1 = math.sqrt(2 * K_B * T1 / M_AR)
        dt = min(0.1 * tau1, 0.2 * tau2, dx / max(u1 + 2 * c_mp1, u2 + 2 * c_mp2))
        flow = L / u2  # slowest flow-through
        warm = int(math.ceil(4 * flow / dt / 100.0)) * 100
        sample = int(math.ceil(20 * flow / dt / 1000.0)) * 1000
        files = 40
        tag = f"shock_ma{M:g}".replace(".", "p")
        text = f"""# Normal shock in argon at Ma {M:g} (docs/verification.md), generated by make_shock_configs.py.
# Upstream n1 = {n1:.4g} m^-3, T1 = {T1:g} K, u1 = {u1:.2f} m/s; Rankine-Hugoniot downstream
# n2/n1 = {r:.5f}, T2/T1 = {tr:.5f}, u2 = {u2:.2f} m/s. lambda1 = {lam1 * 1e3:.4f} mm, tau1 = {tau1:.4g} s,
# tau2 = {tau2:.4g} s. Tube [-30, 30] lambda1, cells lambda1 / 4, {warm} warm-up steps (4 flow-through
# times of the downstream gas), {sample} sampling steps, {files} cell-state files of the sampling phase.
# Evaluate: verification/shock_profile.py results/{tag}
simulation:
  name: {tag}
  mode: dsmc
  random_seed: {20261126 + int(round(10 * M))}

geometry:
  file: marker_cube_1um.stl     # the solver needs a body (1 um, specular: no influence)
  units: m

domain:
  box_min_m: [{-0.5 * L:.9g}, -0.01152, 2.0e-5]    # the 1 um marker cube at (4e-5, -0.0115, 4e-5) lies inside
  box_max_m: [{0.5 * L:.9g}, {-0.01152 + w:.9g}, {2.0e-5 + w:.9g}]

reference:
  area_m2: 1.0
  length_m: 1.0
  moment_center_m: [0.0, 0.0, 0.0]
  lift_axis_body: [0.0, 0.0, 1.0]

gas:                            # upstream state (reference values of the run log)
  number_density_m3: {n1:.6g}
  translational_temperature_K: {T1:g}
  bulk_velocity_body_mps: [{u1:.6f}, 0.0, 0.0]
  species:
    Ar: 1.0

surface:
  model: maxwell
  temperature_K: {T1:g}
  maxwell:
    diffuse_fraction: 0.0

dsmc:
  boundary: specular            # y and z: specular side walls
  faces:
    x_min: {{type: inflow, number_density_m3: {n1:.6g}, temperature_K: {T1:g}, velocity_mps: [{u1:.6f}, 0, 0], fill_depth_m: {0.5 * L:.9g}}}
    x_max: {{type: inflow, number_density_m3: {n2:.6g}, temperature_K: {T2:.6f}, velocity_mps: [{u2:.6f}, 0, 0], fill_depth_m: {0.5 * L:.9g}}}
  collision_model: VHS
  timestep_mode: fixed
  timestep_s: {dt:.4g}
  cell_size_mode: fixed
  cell_size_m: {dx:.9g}
  particles_per_cell_target: {a.ppc}
  warmup_steps: {warm}
  sample_steps: {sample}
  blocks: 10
  dt_DSMCState_out: {sample * dt / files:.6g}
  state_sample_every: 2

statistics:
  confidence_level: 0.95
  report_uncertainty: true

output:
  directory: results/{tag}
  format: json
  save_surface_fields: false
"""
        path = os.path.join(a.out, tag + ".yaml")
        with open(path, "w") as f:
            f.write(text)
        batch.append(f"{tag}.yaml results/{tag}")
        cells = int(round(L / dx)) * 16
        print(f"{tag}: lambda1 {lam1 * 1e3:.3f} mm, dt {dt:.3g} s (tau1 {tau1:.3g}, tau2 {tau2:.3g}), "
              f"{warm} + {sample} steps, ~{cells * a.ppc * (1 + r) / 2 / 1e3:.0f} k particles")
    with open(os.path.join(a.out, "batch_shock.txt"), "w") as f:
        f.write("\n".join(batch) + "\n")


if __name__ == "__main__":
    main()
